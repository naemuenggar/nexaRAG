"""Local-disk file storage for uploaded PDFs.

Files are stored under generated keys (``<owner_id>/<document_id>.pdf``), never under the
user-supplied filename. Uploads are first streamed to a temporary file and only moved into
place once validated, so a rejected or interrupted upload never leaves a visible file.
"""

import asyncio
import os
import uuid
from pathlib import Path


class StorageError(Exception):
    pass


class LocalFileStorage:
    def __init__(self, root: Path) -> None:
        self._root = root.resolve()
        self._incoming = self._root / ".incoming"

    async def ensure_ready(self) -> None:
        await asyncio.to_thread(self._incoming.mkdir, parents=True, exist_ok=True)

    def new_temp_path(self) -> Path:
        return self._incoming / f"{uuid.uuid4().hex}.part"

    @staticmethod
    def document_key(owner_id: uuid.UUID, document_id: uuid.UUID) -> str:
        return f"{owner_id}/{document_id}.pdf"

    def path_for(self, key: str) -> Path:
        path = (self._root / key).resolve()
        # Keys are generated by us, but refuse anything that would escape the root regardless.
        if not path.is_relative_to(self._root) or path == self._root:
            raise StorageError("invalid storage key")
        return path

    async def commit_temp(self, temp_path: Path, key: str) -> None:
        target = self.path_for(key)

        def _move() -> None:
            target.parent.mkdir(parents=True, exist_ok=True)
            os.replace(temp_path, target)

        await asyncio.to_thread(_move)

    async def read_bytes(self, key: str) -> bytes:
        return await asyncio.to_thread(self.path_for(key).read_bytes)

    async def delete(self, key: str) -> None:
        await asyncio.to_thread(self.path_for(key).unlink, missing_ok=True)

    async def discard_temp(self, temp_path: Path) -> None:
        await asyncio.to_thread(temp_path.unlink, missing_ok=True)
